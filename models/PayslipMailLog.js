const mongoose = require('mongoose');

/**
 * One auto payslip email per employee per monthKey (YYYY-MM).
 */
const PayslipMailLogSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    email: {
      type: String,
      required: true,
    },
    monthKey: {
      type: String,
      required: true,
      index: true,
    },
    monthLabel: {
      type: String,
      default: '',
    },
    status: {
      type: String,
      enum: ['sent', 'failed', 'skipped'],
      default: 'sent',
    },
    netPay: {
      type: Number,
      default: 0,
    },
    autoGenerated: {
      type: Boolean,
      default: true,
    },
    errorMessage: {
      type: String,
      default: '',
    },
    sentAt: {
      type: Date,
      default: Date.now,
    },
  },
  { timestamps: true }
);

PayslipMailLogSchema.index({ user: 1, monthKey: 1 }, { unique: true });

module.exports = mongoose.model('PayslipMailLog', PayslipMailLogSchema);
