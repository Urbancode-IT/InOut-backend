/** Stamp Remitted On with the date the payslip is issued / emailed. */
const withRemittedOnIssueDate = (payslip, now = new Date()) => {
  const issued = getIssueDateLabel(now);
  const emp = { ...(payslip?.employeeDetails || {}), remittedOn: issued };
  const snap = payslip?.viewModelSnapshot
    ? { ...payslip.viewModelSnapshot, remittedOn: issued }
    : payslip?.viewModelSnapshot;
  return {
    ...payslip,
    employeeDetails: emp,
    viewModelSnapshot: snap,
  };
};

const alreadySent = async (userId, monthKey) => {
  const existing = await PayslipMailLog.findOne({
    user: userId,
    monthKey,
    status: 'sent',
  })
    .select('_id')
    .lean();
  return Boolean(existing);
};

const claimSlot = async ({ userId, email, monthKey, monthLabel, netPay, autoGenerated }) => {
  const existing = await PayslipMailLog.findOne({ user: userId, monthKey });
  if (existing && existing.status === 'sent') return false;

  if (existing) {
    existing.email = email;
    existing.monthLabel = monthLabel;
    existing.netPay = netPay;
    existing.autoGenerated = autoGenerated;
    existing.status = 'sent';
    existing.errorMessage = '';
    existing.sentAt = new Date();
    await existing.save();
    return true;
  }

  try {
    await PayslipMailLog.create({
      user: userId,
      email,
      monthKey,
      monthLabel,
      netPay,
      autoGenerated,
      status: 'sent',
      sentAt: new Date(),
    });
    return true;
  } catch (err) {
    if (err && (err.code === 11000 || err.code === '11000')) return false;
    throw err;
  }
};

const markFailed = async ({ userId, monthKey, errorMessage }) => {
  await PayslipMailLog.findOneAndUpdate(
    { user: userId, monthKey },
    {
      $set: {
        status: 'failed',
        errorMessage: String(errorMessage || '').slice(0, 500),
      },
    },
    { upsert: true }
  );
};

const sendMail = async ({ to, subject, html, attachments = [] }) => {
  assertEmailConfigured();
  return transporter.sendMail({
    from: getSenderFromAddress(),
    to,
    subject,
    html,
    attachments,
  });
};

const buildPayslipAttachment = async (payslip, monthLabel) => {
  const { buffer, filename } = await buildPayslipPdf(payslip, monthLabel);
  return {
    filename,
    content: buffer,
    contentType: 'application/pdf',
  };
};

const holidayDateKeys = (holidays) => {
  const set = new Set();
  for (const h of holidays) {
    if (!h?.date) continue;
    set.add(
      new Intl.DateTimeFormat('en-CA', {
        timeZone: TIMEZONE,
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
      }).format(new Date(h.date))
    );
  }
  return set;
};

/**
 * Auto-generate payslips and email payslip-only mails for previous IST month.
 * @param {{ now?: Date, dryRun?: boolean, force?: boolean, userId?: string, toEmailOverride?: string }} opts
 */
const runAutoPayslipMails = async ({
  now = new Date(),
  dryRun = false,
  force = false,
  userId = null,
  toEmailOverride = null,
} = {}) => {
  const monthMeta = getPreviousMonthMeta(now);
  const { monthKey, monthLabel, monthStart, monthEnd } = monthMeta;

  let employees = await getEligibleEmployees();
  if (userId) {
    employees = employees.filter((u) => String(u._id) === String(userId));
  }

  const fullUsers = await User.find({
    _id: { $in: employees.map((e) => e._id) },
  })
    .select(
      '_id name email position works role isActive company department employeeId dateOfJoining bankDetails salary phone pan uan esiNumber empGrade'
    )
    .lean();

  const userIds = fullUsers.map((u) => u._id);

  const [schedules, holidays, leaves, allLogs] = await Promise.all([
    Schedule.find({ user: { $in: userIds } }).lean(),
    Holiday.find({
      date: { $gte: monthStart, $lte: monthEnd },
    }).lean(),
    LeaveRequest.find({
      user: { $in: userIds },
      status: 'Approved',
      fromDate: { $lte: monthEnd },
      toDate: { $gte: monthStart },
    }).lean(),
    Attendance.find({
      user: { $in: userIds },
      timestamp: { $gte: monthStart, $lte: monthEnd },
      type: { $in: ['check-in', 'check-out'] },
    })
      .select('user type timestamp')
      .lean(),
  ]);

  const scheduleByUser = new Map(
    schedules.map((s) => [String(s.user), s.weeklySchedule || {}])
  );
  const holidayKeys = holidayDateKeys(holidays);
  const leavesByUser = new Map();
  for (const leave of leaves) {
    const id = String(leave.user);
    if (!leavesByUser.has(id)) leavesByUser.set(id, []);
    leavesByUser.get(id).push(leave);
  }
  const logsByUser = new Map();
  for (const log of allLogs) {
    if (log.user == null) continue;
    const id = String(log.user);
    if (!logsByUser.has(id)) logsByUser.set(id, []);
    logsByUser.get(id).push(log);
  }

  const results = [];

  for (const user of fullUsers) {
    const id = String(user._id);
    const mailTo = toEmailOverride || user.email;

    if (!force && !toEmailOverride && (await alreadySent(user._id, monthKey))) {
      results.push({
        status: 'skipped_duplicate',
        userId: id,
        email: mailTo,
        monthKey,
      });
      continue;
    }

    const attendance = buildEmployeeAttendance({
      logs: logsByUser.get(id) || [],
      weeklySchedule: scheduleByUser.get(id) || {},
      holidayKeys,
      approvedLeaves: leavesByUser.get(id) || [],
      monthMeta,
    });

    let payslip = null;
    let autoGenerated = false;
    try {
      const ensured = await ensurePayslipForMonth(user, attendance.summary, monthMeta, {
        dryRun,
      });
      payslip = ensured.payslip;
      autoGenerated = ensured.autoGenerated;
    } catch (err) {
      console.error(`[PayslipAutoMail] build failed for ${user.email}:`, err.message);
      results.push({
        status: 'failed',
        userId: id,
        email: mailTo,
        monthKey,
        error: err.message,
      });
      continue;
    }

    const payslipForMail = withRemittedOnIssueDate(payslip);
    const html = buildPayslipOnlyHtml({
      name: user.name,
      monthLabel,
      payslip: payslipForMail,
    });
    const subject = `Payslip — ${monthLabel}`;

    if (dryRun) {
      results.push({
        status: 'dry_run',
        userId: id,
        email: mailTo,
        monthKey,
        autoGenerated,
        netPay: payslip?.netPay,
        remittedOn: payslipForMail?.employeeDetails?.remittedOn,
      });
      continue;
    }

    if (!toEmailOverride) {
      if (!force) {
        const claimed = await claimSlot({
          userId: user._id,
          email: mailTo,
          monthKey,
          monthLabel,
          netPay: payslip?.netPay || 0,
          autoGenerated,
        });
        if (!claimed) {
          results.push({
            status: 'skipped_duplicate',
            userId: id,
            email: mailTo,
            monthKey,
          });
          continue;
        }
      } else {
        await PayslipMailLog.findOneAndUpdate(
          { user: user._id, monthKey },
          {
            $set: {
              email: mailTo,
              monthLabel,
              netPay: payslip?.netPay || 0,
              autoGenerated,
              status: 'sent',
              errorMessage: '',
              sentAt: new Date(),
            },
          },
          { upsert: true }
        );
      }
    }

    try {
      const attachment = await buildPayslipAttachment(payslipForMail, monthLabel);
      await sendMail({
        to: mailTo,
        subject,
        html,
        attachments: [attachment],
      });
      results.push({
        status: 'sent',
        userId: id,
        email: mailTo,
        monthKey,
        autoGenerated,
        netPay: payslip?.netPay,
        remittedOn: payslipForMail?.employeeDetails?.remittedOn,
        pdfAttached: true,
      });
    } catch (err) {
      if (!toEmailOverride) {
        await markFailed({
          userId: user._id,
          monthKey,
          errorMessage: err.message,
        });
      }
      results.push({
        status: 'failed',
        userId: id,
        email: mailTo,
        monthKey,
        error: err.message,
      });
    }
  }

  return {
    monthKey,
    monthLabel,
    candidateCount: fullUsers.length,
    results,
  };
};

/**
 * Send one payslip-only test email to an arbitrary address (uses sample/user data).
 */
const sendTestPayslipMail = async ({ toEmail, userEmail = null, now = new Date() } = {}) => {
  assertEmailConfigured();
  const to = String(toEmail || '').trim().toLowerCase();
  if (!to) throw new Error('toEmail is required');

  const monthMeta = getPreviousMonthMeta(now);

  let user = null;
  if (userEmail) {
    user = await User.findOne({ email: String(userEmail).trim().toLowerCase() })
      .select(
        '_id name email position company department employeeId dateOfJoining bankDetails salary phone pan uan esiNumber empGrade'
      )
      .lean();
  }
  if (!user) {
    user = await User.findOne({ email: to })
      .select(
        '_id name email position company department employeeId dateOfJoining bankDetails salary phone pan uan esiNumber empGrade'
      )
      .lean();
  }

  let usedSample = false;
  if (!user) {
    usedSample = true;
    const mongoose = require('mongoose');
    user = {
      _id: new mongoose.Types.ObjectId(),
      name: 'Test Employee',
      email: to,
      position: 'Developer',
      department: 'Engineering',
      company: 'Urbancode',
      employeeId: 'UC-TEST',
      salary: 600000,
      pan: 'ABCDE1234F',
      uan: '100200300400',
      esiNumber: '',
      empGrade: 'L1',
      bankDetails: {},
    };
  }

  const [schedule, holidays, leaves, logs] = await Promise.all([
    Schedule.findOne({ user: user._id }).lean(),
    Holiday.find({
      date: { $gte: monthMeta.monthStart, $lte: monthMeta.monthEnd },
    }).lean(),
    LeaveRequest.find({
      user: user._id,
      status: 'Approved',
      fromDate: { $lte: monthMeta.monthEnd },
      toDate: { $gte: monthMeta.monthStart },
    }).lean(),
    Attendance.find({
      user: user._id,
      timestamp: { $gte: monthMeta.monthStart, $lte: monthMeta.monthEnd },
      type: { $in: ['check-in', 'check-out'] },
    })
      .select('user type timestamp')
      .lean(),
  ]);

  const attendance = buildEmployeeAttendance({
    logs: logs || [],
    weeklySchedule: schedule?.weeklySchedule || {},
    holidayKeys: holidayDateKeys(holidays || []),
    approvedLeaves: leaves || [],
    monthMeta,
  });

  const { payslip } = await ensurePayslipForMonth(user, attendance.summary, monthMeta, {
    dryRun: true,
  });

  const payslipForMail = withRemittedOnIssueDate(payslip);
  const html = buildPayslipOnlyHtml({
    name: user.name,
    monthLabel: monthMeta.monthLabel,
    payslip: payslipForMail,
  });

  const attachment = await buildPayslipAttachment(payslipForMail, monthMeta.monthLabel);
  const info = await sendMail({
    to,
    subject: `[TEST] Payslip — ${monthMeta.monthLabel}`,
    html,
    attachments: [attachment],
  });

  return {
    to,
    messageId: info.messageId,
    monthLabel: monthMeta.monthLabel,
    netPay: payslip?.netPay,
    remittedOn: payslipForMail?.employeeDetails?.remittedOn,
    usedSample,
    userName: user.name,
    pdfFilename: attachment.filename,
  };
};

