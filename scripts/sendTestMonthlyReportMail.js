/**
 * One-off: send a TEST monthly attendance + auto-payslip email.
 *
 *   node scripts/sendTestMonthlyReportMail.js
 *   node scripts/sendTestMonthlyReportMail.js --to=someone@example.com
 */
require('dotenv').config();
const mongoose = require('mongoose');
const transporter = require('../config/emailConfig');
const { getSenderFromAddress, assertEmailConfigured } = require('../config/emailConfig');
const { buildMonthlyReportHtml } = require('../utils/monthlyReportEmails');
const {
  getPreviousMonthMeta,
  buildEmployeeAttendance,
  buildAutoPayslipPayload,
  TIMEZONE,
} = require('../services/monthlyReportService');
const User = require('../models/User');
const Attendance = require('../models/Attendance');
const Schedule = require('../models/Schedule');
const Holiday = require('../models/Holiday');
const LeaveRequest = require('../models/LeaveRequest');

const toArg = process.argv.find((a) => a.startsWith('--to='));
const TO = (toArg ? toArg.split('=')[1] : 'subhikshak.dev@gmail.com').trim().toLowerCase();

const toDateKeyIst = (date) =>
  new Intl.DateTimeFormat('en-CA', {
    timeZone: TIMEZONE,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(date);

(async () => {
  assertEmailConfigured();
  if (!process.env.MONGO_URI) {
    console.error('Missing MONGO_URI');
    process.exit(1);
  }

  await mongoose.connect(process.env.MONGO_URI);
  console.log('Mongo connected');
  console.log('Sending TEST monthly report to:', TO);

  const monthMeta = getPreviousMonthMeta(new Date());

  let user = await User.findOne({ email: TO })
    .select(
      '_id name email position company department employeeId dateOfJoining bankDetails salary phone pan uan esiNumber empGrade'
    )
    .lean();

  let usedSampleProfile = false;
  if (!user) {
    usedSampleProfile = true;
    console.log('No DB user for that email — using sample profile + empty attendance');
    user = {
      _id: new mongoose.Types.ObjectId(),
      name: 'Subhiksha (Test)',
      email: TO,
      position: 'Developer',
      department: 'Engineering',
      company: 'Urbancode',
      employeeId: 'UC-TEST',
      salary: 600000,
      pan: 'ABCDE1234F',
      uan: '100200300400',
      esiNumber: '',
      empGrade: 'L1',
      bankDetails: {},
    };
  } else {
    console.log('Found user:', user.name, String(user._id));
  }

  const [schedule, holidays, leaves, logs] = await Promise.all([
    Schedule.findOne({ user: user._id }).lean(),
    Holiday.find({
      date: { $gte: monthMeta.monthStart, $lte: monthMeta.monthEnd },
    }).lean(),
    LeaveRequest.find({
      user: user._id,
      status: 'Approved',
      fromDate: { $lte: monthMeta.monthEnd },
      toDate: { $gte: monthMeta.monthStart },
    }).lean(),
    Attendance.find({
      user: user._id,
      timestamp: { $gte: monthMeta.monthStart, $lte: monthMeta.monthEnd },
      type: { $in: ['check-in', 'check-out'] },
    })
      .select('user type timestamp')
      .lean(),
  ]);

  const holidayKeys = new Set(
    (holidays || []).filter((h) => h?.date).map((h) => toDateKeyIst(new Date(h.date)))
  );

  const attendance = buildEmployeeAttendance({
    logs: logs || [],
    weeklySchedule: schedule?.weeklySchedule || {},
    holidayKeys,
    approvedLeaves: leaves || [],
    monthMeta,
  });

  const payslip = buildAutoPayslipPayload(user, attendance.summary, monthMeta);
  const html = buildMonthlyReportHtml({
    name: user.name,
    monthLabel: monthMeta.monthLabel,
    attendance,
    payslip,
  });

  const info = await transporter.sendMail({
    from: getSenderFromAddress(),
    to: TO,
    subject: `[TEST] Monthly Report — ${monthMeta.monthLabel} | Attendance & Payslip`,
    html,
  });

  console.log('SENT OK');
  console.log('  to:', TO);
  console.log('  messageId:', info.messageId);
  console.log('  month:', monthMeta.monthLabel);
  console.log('  netPay:', payslip.netPay);
  console.log('  sampleProfile:', usedSampleProfile);
  console.log('  autoGenerated: true (PF/TDS = 0)');

  await mongoose.disconnect();
})().catch(async (err) => {
  console.error('FAILED:', err && err.message ? err.message : err);
  try {
    await mongoose.disconnect();
  } catch (_) {
    /* ignore */
  }
  process.exit(1);
});
